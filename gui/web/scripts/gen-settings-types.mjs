// Generates src/types/settings.generated.ts from the settings JSON schema
// (gui/asserts/mower_config.schema.json), so the settings values have real types instead of `any`.
//
//   cd gui/web && npm run generate:settings-types
//
// `src/test/settings-types.test.ts` fails when the checked-in file drifts from the schema.
import {readFileSync, writeFileSync} from "node:fs";
import {fileURLToPath, pathToFileURL} from "node:url";

/** The TypeScript type of one schema property. */
const tsType = (property) => {
    switch (property.type) {
        case "number":
        case "integer":
            // null: a cleared numeric input.
            return "number | null";
        case "boolean":
            return "boolean";
        case "string":
            return "string";
        default:
            return "unknown";
    }
};

/**
 * Keys the GUI binds but the schema does not describe (the NTRIP credentials live in their own
 * settings card, not in the schema groups). Listed here so they are typed too; a key that later
 * appears in the schema wins.
 */
const EXTRA_KEYS = {
    ntrip_enabled: "boolean",
    ntrip_host: "string",
    ntrip_port: "number | null",
    ntrip_mountpoint: "string",
    ntrip_user: "string",
    ntrip_password: "string",
};

/** The `SettingsValues` source for a schema: every property of every group, flattened. */
export const renderSettingsTypes = (schema) => {
    const types = new Map(Object.entries(EXTRA_KEYS));
    for (const group of Object.values(schema.properties ?? {})) {
        for (const [key, property] of Object.entries(group.properties ?? {})) {
            types.set(key, tsType(property));
        }
    }
    const lines = [...types].map(([key, type]) => `    ${key}?: ${type};`);
    return [
        "// Code generated by scripts/gen-settings-types.mjs from gui/asserts/mower_config.schema.json — DO NOT EDIT.",
        "// Re-run: cd gui/web && npm run generate:settings-types",
        "//",
        "// The settings document is sparse, so every key is optional. Keys the schema does not describe",
        "// stay `unknown` through the index signature.",
        "",
        "export interface SettingsValues {",
        ...lines,
        "    [key: string]: unknown;",
        "}",
        "",
    ].join("\n");
};

// Run as a script (`npm run generate:settings-types`). Importing the module, as the drift test does,
// only needs renderSettingsTypes and must not touch the file system.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const schemaPath = fileURLToPath(new URL("../../asserts/mower_config.schema.json", import.meta.url));
    const outPath = fileURLToPath(new URL("../src/types/settings.generated.ts", import.meta.url));
    const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
    writeFileSync(outPath, renderSettingsTypes(schema));
    console.log(`wrote ${outPath}`);
}
